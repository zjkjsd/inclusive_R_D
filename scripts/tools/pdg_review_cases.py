"""Write the case list for the discussion of the PDG comparison (B0 piece 2).

    python3 scripts/tools/pdg_review_cases.py

reads the result of `pdg_match.build_mode_pdg_table` and the review table, and writes
docs/B0_PIECE2_CASES.md: one numbered case per PDG final-state entry whose comparison with the
decay file needs a look. The hand-written discussion (decisions, reasons) is kept in
docs/B0_PIECE2_REVIEW.md, which refers to the case numbers; this file is regenerated whenever the
matching changes, so do not edit it by hand.
"""
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import decay_table as dt   # noqa: E402
import pdg_match as pm     # noqa: E402

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
OUT = os.path.join(ROOT, 'docs', 'B0_PIECE2_CASES.md')
PROBLEM_FLAGS = ('remainder_unstable', 'remainder_clamped', 'node_not_closed', 'node_ambiguous', 'c_extreme',
                 'limit_capped')
MAIN_SHARE = 5e-4          # cases above this largest yield share are written in full


def _key(text):
    return tuple(int(x) for x in str(text).split())


def _fmt(x, digits=3):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return '–'
    return f'{x:.{digits}g}'


def collect_cases():
    """Return (cases, table). A case is a dict for one PDG final-state node."""
    table, nodes = pm.build_mode_pdg_table(return_nodes=True)
    pdl = dt.load_pdl()
    review = pd.read_csv(pm.DEFAULT_REVIEW_CSV)
    share = {(r.mother_pdg, pm.collapse_key(_key(r.key))): r.max_share for r in review.itertuples()}
    # decay-file line numbers of every final state of the B0 and B+ blocks
    dec = dt.build_mode_table(pdl=pdl).dec
    line_no = {}
    for m, dau, ln, py in zip(dec['mother_pdg'], dec['daughters'], dec['line'], dec['is_pythia']):
        if not py:
            line_no.setdefault((int(m), pm.collapse_key(dau)), []).append(int(ln))
    rows = {}
    for r in table[table['mother_pdg'].isin([511, 521])].itertuples():
        key = _key(r.key) if isinstance(r.key, str) else tuple(r.key)
        rows[(r.mother_pdg, pm.collapse_key(key))] = r

    def name(k):
        return ' '.join('K0' if c == pm.KSYM else pdl.name(c) for c in k)

    cases = []
    for n in nodes[nodes['mother'].isin([511, 521])].itertuples():
        feeders = n.feeders if isinstance(n.feeders, list) else []
        if not feeders or n.kind == 'product' or n.role in ('exact', 'limit', 'capped', 'multi_ks'):
            continue
        if str(n.uid).endswith('[mu]'):
            continue                                    # the muon copy of a lepton node
        lines, max_share, problem = [], 0.0, False
        for k, fed, bf in feeders:
            x = rows.get((n.mother, k))
            if x is None:
                continue
            flags = x.flags if isinstance(x.flags, str) else ''
            ids = x.pdgids if isinstance(x.pdgids, str) else ''
            uses = n.pdgid in ids.split(';')
            sh = share.get((n.mother, k), 0.0) or 0.0
            if fed / bf >= pm.P_MIN:
                max_share = max(max_share, sh)
            if uses and any(f in flags for f in PROBLEM_FLAGS):
                problem = True
            lines.append(dict(name=name(k), line=', '.join(str(x) for x in sorted(line_no.get((n.mother, k), []))), bf=bf, p=fed / bf, how=x.how if isinstance(x.how, str) else '',
                              ids=ids, c=x.c, sigma=x.sigma_c, flags=flags, share=sh, uses=uses,
                              cls=x.pdg_class))
        not_closed = pd.notna(n.closure_pull) and abs(n.closure_pull) > 3
        if problem or not_closed:
            cases.append(dict(node=n, lines=lines, share=max_share, not_closed=not_closed))
    cases.sort(key=lambda c: (-c['share'], c['node'].pdgid))
    return cases, table


def write_cases(path=OUT):
    cases, _ = collect_cases()
    main = [c for c in cases if c['share'] >= MAIN_SHARE]
    rest = [c for c in cases if c['share'] < MAIN_SHARE]
    out = ['# B0 piece 2: cases of the PDG comparison to check',
           '',
           'Generated by `scripts/tools/pdg_review_cases.py`; do not edit by hand. Decisions and their',
           'reasons are in `docs/B0_PIECE2_REVIEW.md`. Case numbers change whenever the file is',
           'regenerated (they follow the ranking); refer to a case by its PDG entry.',
           '',
           '## What a case is',
           '',
           'PDG often quotes a branching fraction for a final state as a whole, for example',
           'B⁰ → D⁻π⁺π⁺π⁻, whatever intermediate resonances produced it. The decay file can produce the',
           'same final state through several lines: a direct line and lines with a resonance that',
           'decays to it (D⁻a₁⁺ with a₁⁺ → π⁺π⁺π⁻). To compare the two, the code adds up all decay-file',
           'lines that end in the PDG final state.',
           '',
           'A **case** is one such PDG entry where this comparison does not work out. There are two',
           'ways it can fail:',
           '',
           '1. a decay-file line took its correction c from this entry, and the result carries a',
           '   warning: c far from 1 (`c_extreme`), a remainder less than 1σ from 0 or clamped at 0',
           '   (`remainder_unstable`, `remainder_clamped`), another entry it could have used',
           '   (`node_ambiguous`), or its own limit exceeded (`limit_capped`);',
           '2. after every line is multiplied by its c, the decay-file sum still differs from the PDG',
           '   value by more than 3σ. The case is then marked **not closed**.',
           '',
           'Each case shows the PDG entry, the decay-file sum, and a table of the decay-file lines that',
           'feed it. A line can appear in several cases, because it can feed several final states.',
           '',
           f'The cases are ordered by importance: the largest share that any of their lines has in the',
           f'exclusive yield of one of the 72 sample tables. {len(main)} cases reach {100 * MAIN_SHARE:g} % and are written',
           f'in full; the other {len(rest)} are in one table at the end.',
           '',
           '## How to read a case',
           '',
           'Header of a case:',
           '',
           '| Item | Meaning |',
           '|---|---|',
           '| PDG | value and error of the PDG entry |',
           '| MC sum | what the decay file gives for the same final state: the sum over the lines of BF × P |',
           '| after c | the same sum with every line multiplied by its c; "after c / PDG" should be 1 |',
           '',
           'Columns of the line table:',
           '',
           '| Column | Meaning |',
           '|---|---|',
           '| Line | the decay-file line, by its daughters |',
           '| dec line | line number in `Samples/dec/DECAY_BELLE2_rel08.DEC` (B⁰ or B⁺ block; e mode for a lepton entry; for K⁰ final states all of the K⁰, K_S⁰, K_L⁰ lines, including BF = 0 ones) |',
           '| BF | branching fraction of the line in the decay file |',
           '| P | fraction of the line that ends in the final state of this case (1 for the direct line) |',
           '| class | `measured`, `limit` (PDG has only an upper limit) or `none` (no PDG entry, `unmeasured`, or vetoed) |',
           '| how | where the c of the line comes from: `exact` = a PDG entry for exactly this line; `product` = a PDG entry B(B → X Y) × B(X → …); `node` = the line is the direct (phase-space) line of a multi-body PDG entry and takes its remainder; `isospin`, `half_limit`, `veto` = by exception (register in section 3 of the review file); empty = no c (`unmeasured` lines: c = 1 ± 1) |',
           '| PDG id | the PDG entry or entries used for the c |',
           '| c, ± | c = BF_PDG / BF_MC and its uncertainty |',
           '| this entry | "yes" if the c of the line comes from the entry of this case |',
           '| flags | warnings; explained in section 0 of the review file |',
           '| share % | largest share of the line in the exclusive yield of any sample table |',
           '']
    for i, c in enumerate(main, start=1):
        n = c['node']
        lep = ' (same for the muon)' if str(n.uid).endswith('[e]') else ''
        out += [f'## Case {i}: {n.pdgid}, {n.description}{lep}',
                '',
                f'- PDG: {_fmt(n.value)} ± {_fmt(n.err, 2)}',
                f'- MC sum: {_fmt(n.bf_mc)} (PDG / MC = {_fmt(n.ratio)})',
                f'- after c: {_fmt(n.bf_mc_weighted)} (after c / PDG = {_fmt(n.closure)}, '
                f'{_fmt(n.closure_pull, 2)}σ)' + ('; **not closed**' if c['not_closed'] else ''),
                f'- largest yield share of its lines: {100 * c["share"]:.2f} %',
                '',
                '| Line | dec line | BF | P | class | how | PDG id | c | ± | this entry | flags | share % |',
                '|---|---|---|---|---|---|---|---|---|---|---|---|']
        for ln in c['lines']:
            out.append(f"| {ln['name']} | {ln['line']} | {_fmt(ln['bf'])} | {ln['p']:.2f} | {ln['cls']} | {ln['how']} | "
                       f"{ln['ids'].replace(';', ', ')} | {_fmt(ln['c'])} | {_fmt(ln['sigma'], 2)} | "
                       f"{'yes' if ln['uses'] else ''} | {ln['flags'].replace(';', ', ')} | {100 * ln['share']:.2f} |")
        out.append('')
    out += ['## Other cases (yield share below the threshold)',
            '',
            '| PDG id | Entry | PDG | MC sum | after c / PDG | σ | lines using it [dec line] (c) | share % |',
            '|---|---|---|---|---|---|---|---|']
    for c in rest:
        n = c['node']
        using = '; '.join(f"{ln['name']} [{ln['line']}] ({_fmt(ln['c'])})" for ln in c['lines'] if ln['uses']) or '–'
        out.append(f"| {n.pdgid} | {n.description} | {_fmt(n.value)} ± {_fmt(n.err, 2)} | {_fmt(n.bf_mc)} | "
                   f"{_fmt(n.closure)} | {_fmt(n.closure_pull, 2)} | {using} | {100 * c['share']:.3f} |")
    out.append('')
    with open(path, 'w') as f:
        f.write('\n'.join(out))
    return len(main), len(rest)


if __name__ == '__main__':
    n_main, n_rest = write_cases()
    print(f'wrote {OUT}: {n_main} cases in full, {n_rest} in the table')
