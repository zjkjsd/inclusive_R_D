# --------------------------------------------------------------------------------------------
# Particle list
# --------------------------------------------------------------------------------------------
class ParticleTable:
    """Names, PDG codes and charges from an evt.pdl file.

    Attributes
    ----------
    name_to_pdg : dict, EvtGen name -> signed PDG code.
    pdg_to_name : dict, the reverse.
    charge3     : dict, PDG code -> 3 x charge.
    inclusive   : set of PDG codes of the inclusive pseudo-particles (`INCLUSIVE_NAMES`).
    """

    def __init__(self, path=DEFAULT_PDL):
        self.path = path
        self.name_to_pdg, self.pdg_to_name, self.charge3 = {}, {}, {}
        with open(path) as f:
            for line in f:
                t = line.split()
                # add  p Particle  <name>  <id>  <mass>  <width>  <max_Dm>  <3*charge>  <2*spin> ...
                if len(t) < 9 or t[0] != 'add' or t[2] != 'Particle':
                    continue
                name, pdg, q3 = t[3], int(t[4]), int(t[8])
                if name in self.name_to_pdg:
                    raise ValueError(f'{path}: particle {name!r} is defined twice')
                self.name_to_pdg[name] = pdg
                self.pdg_to_name.setdefault(pdg, name)
                self.charge3[pdg] = q3
        if not self.name_to_pdg:
            raise ValueError(f'{path}: no particle definitions found')
        self.inclusive = {self.name_to_pdg[n] for n in INCLUSIVE_NAMES if n in self.name_to_pdg}

    def name(self, pdg):
        """EvtGen name of a PDG code ('?<code>' if unknown)."""
        return self.pdg_to_name.get(int(pdg), f'?{int(pdg)}')

    def names(self, pdgs):
        """Names of a list of PDG codes, as one string."""
        return ' '.join(self.name(p) for p in pdgs if p != EMPTY)

    def conjugate(self, pdg):
        """PDG code of the antiparticle (the code itself for self-conjugate particles)."""
        return -pdg if -pdg in self.pdg_to_name else pdg


def load_pdl(path=DEFAULT_PDL):
    """Read an evt.pdl file. See `ParticleTable`."""
    return ParticleTable(path)


