# Quark content from the PDG code
# --------------------------------------------------------------------------------------------
# Exotic charmonium-like states whose code does not follow the quark-digit rule.
_CHARMONIUM_LIKE = (9042413,)          # Z(4430)+


def _quark_digits(pdg):
    """(nq1, nq2, nq3) of the PDG numbering scheme, as arrays; zeros for everything that is not
    a meson or a baryon (leptons, quarks, diquarks, nuclei, pseudo-particles below 100)."""
    a = np.abs(np.asarray(pdg, dtype=np.int64))
    nq1, nq2, nq3 = (a // 1000) % 10, (a // 100) % 10, (a // 10) % 10
    hadron = (a > 100) & (a < 1_000_000_000) & (nq2 != 0) & (nq3 != 0)   # nq3 = 0: diquark
    hadron &= ~np.isin(a, _CHARMONIUM_LIKE)
    hadron &= ~((a >= 80_000) & (a < 100_000))      # generator-specific codes (B0long, B0heavy, ...)
    nq1 = np.where(a >= 9_000_000, 0, nq1)          # exotic mesons (Z_b): the thousands digit is no quark
    # K_S0 (310) and K_L0 (130) do not follow the scheme and drop out here; they have no charm
    # and are not baryons, so the rules below still give the right answer for them.
    return np.where(hadron, nq1, 0), np.where(hadron, nq2, 0), np.where(hadron, nq3, 0)


def _not_inclusive(pdg, inclusive):
    if not len(inclusive):
        return True
    return ~np.isin(np.abs(pdg), np.abs(list(inclusive)))


def is_open_charm(pdg, inclusive=()):
    """True for hadrons with net charm: D, D*, D**, D_s(*,**), B_c, charm baryons. Not charmonium.

    inclusive : PDG codes of the inclusive pseudo-particles (`ParticleTable.inclusive`). Their
    codes look like hadron codes (Xsd = 30343), so they are excluded explicitly.
    """
    nq1, nq2, nq3 = _quark_digits(pdg)
    n_c = (nq1 == 4).astype(int) + (nq2 == 4).astype(int) + (nq3 == 4).astype(int)
    return np.where(nq1 == 0, n_c == 1, n_c >= 1) & _not_inclusive(pdg, inclusive)


def is_charmonium(pdg, inclusive=()):
    """True for c cbar mesons (J/psi, psi(2S), eta_c, chi_c, h_c, X(3872), Z(4430))."""
    nq1, nq2, nq3 = _quark_digits(pdg)
    out = (nq1 == 0) & (nq2 == 4) & (nq3 == 4)
    out |= np.isin(np.abs(np.asarray(pdg, dtype=np.int64)), _CHARMONIUM_LIKE)
    return out & _not_inclusive(pdg, inclusive)


def is_baryon(pdg, inclusive=()):
    """True for baryons."""
    nq1, nq2, nq3 = _quark_digits(pdg)
    return (nq1 != 0) & _not_inclusive(pdg, inclusive)


# --------------------------------------------------------------------------------------------
# Keys
# --------------------------------------------------------------------------------------------
def canonical_order(d):
    """Sort each row of an (n, k) integer array into canonical order.

    Canonical order: by |PDG|, particle before antiparticle, empty slots (-1) last. It is the order
    of the `daughter_i` columns of `utilities.decay_mode_table`.
    """
    d = np.asarray(d, dtype=np.int64)
    key = np.where(d == EMPTY, np.iinfo(np.int64).max, np.abs(d) * 2 + (d < 0))
    return np.take_along_axis(d, np.argsort(key, axis=1, kind='stable'), axis=1)


def mode_key(daughters):
    """Key of one final state: the tuple of its PDG codes in canonical order."""
    d = [int(x) for x in daughters if int(x) != EMPTY]
    return tuple(sorted(d, key=lambda x: (abs(x), x < 0)))


# --------------------------------------------------------------------------------------------
# Decay file
# --------------------------------------------------------------------------------------------
def _split_statement(line):
    """Split a decay-file line into (statement, comment). The statement ends at the first ';'
    or '#', whichever comes first."""
    i_hash = line.find('#')
    i_semi = line.find(';')
    if i_semi != -1 and (i_hash == -1 or i_semi < i_hash):
        return line[:i_semi].strip(), line[i_semi + 1:].strip(' ;\t\n')
    if i_hash != -1:
        return line[:i_hash].strip(), line[i_hash:].strip()
    return line.strip(), ''


def parse_dec(path=DEFAULT_DEC, mothers=B_MOTHERS, pdl=None, extra_models=()):
    """Parse the decay blocks of `mothers` in an EvtGen decay file.

    Parameters
    ----------
    path : decay file.
    mothers : names of the decaying particles to read; None reads every block.
    pdl : `ParticleTable`, or None to read the default evt.pdl.
    extra_models : decay-model names to accept in addition to `KNOWN_MODELS`.

    Returns
    -------
    DataFrame, one row per decay line, in file order:
      mother, mother_pdg : decaying particle (alias names are kept in `mother`).
      line        : line number in the file (1-based). For lines created by a CDecay statement it
                    is the line of the original decay.
      bf          : branching fraction as written.
      names       : tuple of daughter names as written (aliases kept).
      daughters   : tuple of signed PDG codes in the order of the line, aliases resolved.
      key         : the same in canonical order (see `mode_key`).
      n_daughters : number of daughters.
      model, model_args : decay model and its arguments (one string).
      photos      : True if the line carries the PHOTOS keyword.
      is_pythia   : True for quark-level PYTHIA lines (model PYTHIA; daughters are quarks, gluons
                    or diquarks, or none).
      comment     : text after the ';'.
      directive   : the '#$ ...' line directly above, if any (e.g. 'forbid_pythia()').
      from_cdecay : True for lines created by a CDecay statement.
    The aliases and the block sums are in `.attrs['aliases']` and `.attrs['bf_sum']`.

    Raises ValueError if the token after the daughters is not a known decay model, so that a
    particle missing from the particle list is never taken silently for the model; also for a line
    inside a block that does not start with a number. As in EvtGen, a second Decay block of the
    same particle replaces the first (with a warning), and CDecay copies the conjugate block as
    it stands at that line.
    """
    pdl = pdl or load_pdl()
    with open(path) as f:
        text = f.read().splitlines()

    # first pass: aliases and charge-conjugate pairs (they may be used before they are defined)
    alias, conj_pair, model_alias = {}, {}, set()
    for line in text:
        t = line.split('#')[0].split()
        if len(t) >= 3 and t[0] == 'Alias':
            alias[t[1]] = t[2]
        elif len(t) >= 3 and t[0] == 'ModelAlias':
            model_alias.add(t[1])
        elif len(t) >= 3 and t[0] == 'ChargeConj':
            conj_pair[t[1]], conj_pair[t[2]] = t[2], t[1]

    models = KNOWN_MODELS | model_alias | set(extra_models)

    def base_name(name):
        seen = set()
        while name in alias and name not in seen:
            seen.add(name)
            name = alias[name]
        return name

    def is_particle(tok):
        return base_name(tok) in pdl.name_to_pdg

    def conj_name(name):
        if name in conj_pair:
            return conj_pair[name]
        if name in alias:
            # an alias without a ChargeConj statement is its own conjugate; EvtGen allows this
            # only if the particle behind it is self-conjugate
            pdg = pdl.name_to_pdg[base_name(name)]
            if pdl.conjugate(pdg) != pdg:
                raise ValueError(f'{path}: alias {name!r} of a particle with a distinct antiparticle '
                                 f'has no ChargeConj statement; its conjugate is not defined')
            return name
        pdg = pdl.name_to_pdg[name]
        return pdl.pdg_to_name[pdl.conjugate(pdg)]

    def conjugate_block(name, i):
        known = name in conj_pair or name in alias or name in pdl.name_to_pdg
        partner = conj_name(name) if known else None
        if partner is None or partner not in blocks:
            raise ValueError(f'{path}:{i}: CDecay {name}: no Decay block of its conjugate above')
        return [dict(r, mother=name, names=tuple(conj_name(n) for n in r['names']),
                     from_cdecay=True) for r in blocks[partner]]

    rows, blocks = [], {}
    current, directive = None, ''
    for i, raw in enumerate(text, start=1):
        s = raw.strip()
        if not s:
            directive = ''
            continue
        if s.startswith('#$'):
            directive = s[2:].strip()
            continue
        if s.startswith('#'):
            continue
        stmt, comment = _split_statement(raw)
        t = stmt.split()
        if not t:
            continue
        if comment and not comment.startswith('#'):
            warnings.warn(f'{path}:{i}: text after the ";" is not a comment and is ignored: '
                          f'{comment!r}')
        if t[0] == 'Decay' and len(t) >= 2:
            current = t[1]
            if not is_particle(current):
                raise ValueError(f'{path}:{i}: Decay {current}: unknown particle')
            if current in blocks:               # EvtGen: a later block replaces the earlier one
                warnings.warn(f'{path}:{i}: the decay of {current} is defined again; the earlier '
                              f'definition is dropped')
            blocks[current] = []
            directive = ''
            continue
        if t[0] == 'Enddecay':
            current, directive = None, ''
            continue
        if t[0] == 'CDecay' and len(t) >= 2:
            blocks[t[1]] = conjugate_block(t[1], i)     # conjugate of the block as it stands here
            directive = ''
            continue
        if current is None:
            directive = ''
            continue                            # global statement (Alias, Define, yesPhotos, ...)
        if not _NUMBER.match(t[0]):
            raise ValueError(f'{path}:{i}: inside the decay of {current}, the line does not start '
                             f'with a branching fraction: {s}')

        bf = float(t[0])
        names, j = [], 1
        while j < len(t) and is_particle(t[j]):
            names.append(t[j])
            j += 1
        photos = False
        while j < len(t) and t[j] == 'PHOTOS':
            photos = True
            j += 1
        if j >= len(t) or t[j] not in models:
            bad = t[j] if j < len(t) else '<end of line>'
            raise ValueError(f'{path}:{i}: {bad!r} is neither a known particle nor a known decay '
                             f'model (line: {s}). If it is a particle, it is missing from '
                             f'{pdl.path}; if it is a model, pass it in extra_models.')
        if not names and t[j] != 'PYTHIA':
            raise ValueError(f'{path}:{i}: decay line without daughters: {s}')
        row = dict(mother=current, line=i, bf=bf, names=tuple(names), model=t[j],
                   model_args=' '.join(t[j + 1:]), photos=photos, comment=comment,
                   directive=directive, from_cdecay=False)
        blocks[current].append(row)
        directive = ''

    wanted = list(blocks) if mothers is None else list(mothers)
    missing = [m for m in wanted if m not in blocks]
    if missing:
        raise ValueError(f'{path}: no decay block for {missing}')
    for m in wanted:
        rows.extend(blocks[m])

    out = pd.DataFrame(rows)
    out['mother_pdg'] = [pdl.name_to_pdg[base_name(m)] for m in out['mother']]
    out['daughters'] = [tuple(pdl.name_to_pdg[base_name(n)] for n in ns) for ns in out['names']]
    out['key'] = [mode_key(d) for d in out['daughters']]
    out['n_daughters'] = [len(d) for d in out['daughters']]
    # PYTHIA lines of the B blocks: model PYTHIA with quark or diquark daughters. (Other particles
    # also use the PYTHIA model with hadron daughters, e.g. the tau; those lines are final states.)
    parton = [all(abs(p) < 10 or abs(p) == 21 or (1000 < abs(p) < 6000 and (abs(p) // 10) % 10 == 0)
                  for p in d) for d in out['daughters']]
    out['is_pythia'] = (out['model'] == 'PYTHIA') & np.array(parton, dtype=bool)
    cols = ['mother', 'mother_pdg', 'line', 'bf', 'names', 'daughters', 'key', 'n_daughters', 'model',
            'model_args', 'photos', 'is_pythia', 'comment', 'directive', 'from_cdecay']
    out = out[cols]
    out.attrs['aliases'] = dict(alias)
    out.attrs['bf_sum'] = out.groupby('mother', sort=False)['bf'].sum().to_dict()
    out.attrs['path'] = path
    return out


# --------------------------------------------------------------------------------------------
# Mode table
# --------------------------------------------------------------------------------------------
class ModeTable:
    """Exclusive final states of the B mesons, ready for lookup.

    Attributes
    ----------
    modes : DataFrame, one row per (mother_pdg, key):
        bf_mc      : summed BF of the lines with this final state (alias lines such as K*S, K*L
                     and K*0T share one final state).
        lines      : tuple of their line numbers.
        orders     : tuple of the distinct daughter orders of those lines.
        zero_bf    : True if the summed BF is 0 (the final state is only vetoed for PYTHIA).
        n_daughters, is_sl, sl_lepton, n_charm, n_charmonium, n_baryon, is_inclusive, has_photon.
    pythia : DataFrame of the PYTHIA lines (quark-level; not final states).
    pythia_bf : dict mother_pdg -> summed BF of the PYTHIA lines.
    exclusive_bf : dict mother_pdg -> summed BF of the exclusive lines.
    lookup : dict (mother_pdg, key) -> row position in `modes`.
    max_daughters : largest number of daughters of an exclusive line.
    """

    def __init__(self, dec, pdl):
        self.pdl = pdl
        self.dec = dec
        n_names = dec.groupby('mother_pdg')['mother'].nunique()
        if (n_names > 1).any():
            raise ValueError('ModeTable: several decay blocks share a PDG code (alias mothers such as '
                             'B0sig and B0); build the table from one block per particle. Codes: '
                             f'{list(n_names[n_names > 1].index)}')
        excl = dec[~dec['is_pythia']]
        self.pythia = dec[dec['is_pythia']].reset_index(drop=True)
        self.pythia_bf = self.pythia.groupby('mother_pdg')['bf'].sum().to_dict()
        self.exclusive_bf = excl.groupby('mother_pdg')['bf'].sum().to_dict()

        rows = []
        for (m, key), g in excl.groupby(['mother_pdg', 'key'], sort=False):
            orders = tuple(dict.fromkeys(g['daughters']))        # distinct, in file order
            rows.append(dict(mother_pdg=m, key=key, bf_mc=g['bf'].sum(), lines=tuple(g['line']),
                             orders=orders, n_daughters=len(key)))
        modes = pd.DataFrame(rows)
        modes['zero_bf'] = modes['bf_mc'] == 0
        props = [decay_properties(np.array(k, dtype=np.int64)[None, :], pdl) for k in modes['key']]
        for c in ('is_sl', 'sl_lepton', 'n_charm', 'n_charmonium', 'n_baryon', 'is_inclusive'):
            modes[c] = [p[c][0] for p in props]
        modes['has_photon'] = [PHOTON in k for k in modes['key']]
        self.modes = modes
        self.lookup = {(m, k): i for i, (m, k) in enumerate(zip(modes['mother_pdg'], modes['key']))}
        self.max_daughters = int(modes['n_daughters'].max())

    def get(self, mother_pdg, key):
        """Row of `modes` for a final state, or None."""
        i = self.lookup.get((int(mother_pdg), tuple(key)))
        return None if i is None else self.modes.iloc[i]


def build_mode_table(dec=None, pdl=None):
    """Group the exclusive lines of a parsed decay file by final state. See `ModeTable`.

    With no arguments, the default decay file and particle list are read.
    """
    pdl = pdl or load_pdl()
    if dec is None:
        dec = parse_dec(pdl=pdl)
    return ModeTable(dec, pdl)


# --------------------------------------------------------------------------------------------
# Properties of a daughter list
# --------------------------------------------------------------------------------------------
def decay_properties(d, pdl):
    """Properties of B-daughter lists that depend only on the daughters.

    d : (n, k) integer array of PDG codes, -1 for empty slots.
    Returns a dict of arrays:
      is_sl        : a charged lepton and a neutrino among the daughters.
      sl_lepton    : 11, 13 or 15 for semileptonic decays, else 0.
      n_charm      : number of open-charm hadrons (see `is_open_charm`).
      n_charmonium : number of c cbar mesons.
      n_baryon     : number of baryons.
      is_inclusive : an inclusive pseudo-particle (Xu, Xsd, ...) among the daughters.
    """
    d = np.asarray(d, dtype=np.int64)
    a = np.abs(d)
    filled = d != EMPTY
    lep = np.isin(a, CHARGED_LEPTONS) & filled
    nu = np.isin(a, NEUTRINOS) & filled
    is_sl = lep.any(axis=1) & nu.any(axis=1)
    sl_lepton = np.where(is_sl, np.where(lep, a, 0).max(axis=1), 0)
    incl = pdl.inclusive
    return dict(
        is_sl=is_sl,
        sl_lepton=sl_lepton,
        n_charm=(is_open_charm(d, incl) & filled).sum(axis=1),
        n_charmonium=(is_charmonium(d, incl) & filled).sum(axis=1),
        n_baryon=(is_baryon(d, incl) & filled).sum(axis=1),
        is_inclusive=(np.isin(a, np.abs(list(incl))) & filled).any(axis=1),
    )


def _charge3(d, pdl):
    """(3 x summed charge, all codes known) of each row of d."""
    q = np.zeros(d.shape[0], dtype=np.int64)
    known = np.ones(d.shape[0], dtype=bool)
    for code in np.unique(d):
        if code == EMPTY:
            continue
        m = d == code
        if int(code) in pdl.charge3:
            q += m.sum(axis=1) * pdl.charge3[int(code)]
        else:
            known &= ~m.any(axis=1)
    return q, known


