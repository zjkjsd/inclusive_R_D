"""Decay-table parser and generator classification of B decays (step B0, piece 1).

What it does
------------
1. `load_pdl` reads EvtGen's particle list (evt.pdl): name -> PDG code and charge.
2. `parse_dec` reads an EvtGen decay file: one row per decay line of the requested mothers.
3. `build_mode_table` groups the exclusive lines of each B by final state (the set of daughters).
4. `classify_decays` looks up B-daughter lists from the MC truth in that table and tells whether the
   decay was generated by EvtGen from an exclusive line or by PYTHIA.

Why a lookup is enough
----------------------
In the Belle II generic MC, PYTHIA is not allowed to produce a final state that is listed as an
exclusive channel of the same B (zero-BF lines included); it retries until the final state is new.
So the exclusive and the PYTHIA final states are disjoint: a daughter set that is in the decay file
comes from EvtGen, any other comes from PYTHIA. EvtGen stores the daughters in the order of the
decay-file line, PHOTOS appends its photons at the end. `validation_report` tests this mechanism
on every sample that is classified (see there for what it can't test).

Conventions
-----------
* A final state is identified by its "key": the tuple of signed PDG codes in canonical order
  (by |PDG|, particle before antiparticle). This is the order of the `daughter_i` columns written
  by `utilities.decay_mode_table`.
* All four B blocks are used as written. The conjugate blocks of the decay file are not exact
  mirrors of each other, so one is never derived from the other.
* The B flavor is not stored in the ntuples. For a charged B it follows from the charge of the
  daughters. For a neutral B it is taken from the block that lists the final state, when only one
  does.

The module needs numpy and pandas only.
"""
